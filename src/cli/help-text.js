const commands = [
  ["scan", "Scan the project and write markdown, JSON, latest, and history reports."],
  ["diff", "Scan the current git diff surface and write reports."],
  ["ci", "Scan the project and exit with code 1 when block-policy findings are present."],
  ["baseline", "Save the current findings as accepted existing debt."],
  ["report", "Print the latest markdown report."],
  ["history", "List saved scan versions."],
  ["compare", "Compare the latest two scan versions, or versions selected with --from and --to."],
  ["maturity", "Print a read-only maturity summary from the latest report."],
  ["explain", "Write AI-ready analysis files from the latest report."],
  ["watch", "Run scan repeatedly at a fixed interval."]
];

export function shortHelpText() {
  return [
    "Guardrails - code health radar for AI-assisted development.",
    "",
    "Usage:",
    "  guardrails <command> [options]",
    "  guardrails --help",
    "  guardrails help details",
    "",
    "Commands:",
    ...commands.map(([name, description]) => `  ${name.padEnd(10)} ${description}`),
    "",
    "Common options:",
    "  -p, --path <dir>     Project path. Defaults to the current directory.",
    "  -h, --help           Show this help.",
    "  --details            Show the detailed manual.",
    "",
    "Examples:",
    "  guardrails scan --path .",
    "  guardrails ci --path .",
    "  guardrails explain --path /path/to/project",
    "",
    "Run `guardrails help details` for the full manual."
  ].join("\n");
}

